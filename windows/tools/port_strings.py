"""Regenerates windows/Swivel/Core/Strings.Mac.cs from the macOS Strings.table (Sources/Swivel/Localization.swift).

Run from the repository root: python windows/tools/port_strings.py
"""
import re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
src = (root / "Sources/Swivel/Localization.swift").read_text(encoding="utf-8").replace(chr(13), "")
body = src[src.index("static let table"):]
body = body[body.index("= [") + 3:]

def unescape(s):
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            if n == "u" and s[i + 2] == "{":
                j = s.index("}", i)
                out.append(chr(int(s[i + 3:j], 16))); i = j + 1; continue
            out.append({"n": "\n", "t": "\t", "0": "\0", "\\": "\\", '"': '"', "'": "'"}.get(n, n)); i += 2; continue
        out.append(c); i += 1
    return "".join(out)

tokens, i = [], 0
while i < len(body):
    c = body[i]
    if body.startswith('"""', i):
        end = body.index('"""', i + 3)
        while body[end - 1] == "\\":
            end = body.index('"""', end + 1)
        raw = body[i + 3:end]
        lines = raw.split("\n")[1:]  # content starts after the opening line
        indent = lines[-1]          # the closing delimiter's indentation
        lines = lines[:-1]
        text = ""
        for k, line in enumerate(lines):
            line = line[len(indent):] if line.startswith(indent) else line.lstrip()
            if line.endswith("\\") and not line.endswith("\\\\"):
                text += line[:-1]
            else:
                text += line + ("\n" if k < len(lines) - 1 else "")
        tokens.append(("s", unescape(text))); i = end + 3
    elif c == '"':
        j = i + 1
        while body[j] != '"':
            j += 2 if body[j] == "\\" else 1
        tokens.append(("s", unescape(body[i + 1:j]))); i = j + 1
    elif body.startswith("//", i):
        i = body.index("\n", i)
    elif c in ":[],":
        tokens.append((c, c)); i += 1
    elif c == "]" or c.isspace():
        i += 1
    else:
        break  # end of the dictionary literal

rows, k = [], 0
while k + 8 < len(tokens) and tokens[k][0] == "s":
    key = tokens[k][1]
    assert tokens[k + 1][0] == ":" and tokens[k + 2][0] == "[", tokens[k:k + 3]
    vals = [tokens[k + 3][1], tokens[k + 5][1], tokens[k + 7][1]]
    assert tokens[k + 8][0] == "]", tokens[k + 8]
    rows.append((key, vals))
    k += 9
    if k < len(tokens) and tokens[k][0] == ",":
        k += 1

def cs(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'

out = ["// <auto-generated> by windows/tools/port_strings.py from Sources/Swivel/Localization.swift. Do not edit;",
       "// add Windows-only strings to the other Strings.*.cs files instead. </auto-generated>",
       "namespace Swivel;", "", "static partial class Strings", "{",
       "    /// English → [简体中文, 繁體中文, 日本語], shared with the macOS app.",
       "    static partial (string English, string[] Translations)[] Mac => [" ]
for key, vals in rows:
    out.append(f"        ({cs(key)}, [{', '.join(cs(v) for v in vals)}]),")
out += ["    ];", "}", ""]
dest = root / "windows/Swivel/Core/Strings.Mac.cs"
dest.write_text("\n".join(out), encoding="utf-8")
print(f"{len(rows)} rows -> {dest}")
